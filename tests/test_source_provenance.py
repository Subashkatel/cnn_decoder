"""Source provenance is independent of archives and local bytecode caches."""

from pathlib import Path
import tempfile
import unittest

from training_data.reports import source_tree_hash


class SourceProvenanceTests(unittest.TestCase):
    def test_source_content_changes_the_fingerprint(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory)
            module = source / "builder.py"
            module.write_text("VALUE = 1\n")
            original = source_tree_hash(source)
            module.write_text("VALUE = 2\n")
            changed = source_tree_hash(source)
            self.assertNotEqual(original, changed)

    def test_source_names_matter_but_bytecode_caches_do_not(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory)
            module = source / "builder.py"
            module.write_text("VALUE = 1\n")
            original = source_tree_hash(source)
            cache = source / "__pycache__"
            cache.mkdir()
            (cache / "builder.pyc").write_bytes(b"generated bytecode")
            after_cache = source_tree_hash(source)
            self.assertEqual(original, after_cache)
            module.rename(source / "renamed.py")
            after_rename = source_tree_hash(source)
            self.assertNotEqual(original, after_rename)

    def test_a_missing_source_directory_is_not_a_valid_fingerprint(self):
        with tempfile.TemporaryDirectory() as directory:
            missing = Path(directory) / "missing"
            with self.assertRaises(FileNotFoundError):
                source_tree_hash(missing)
